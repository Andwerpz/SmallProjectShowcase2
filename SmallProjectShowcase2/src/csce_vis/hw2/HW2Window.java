	class Particle {
		Vec3 pos, vel, hue;
		float lifespan, air_friction_coeff, coeff_restitution;
		boolean is_static, proximity_hue;

		public Particle(Vec3 _pos) {
			this(_pos, new Vec3(0));
			this.is_static = true;
		}

		public Particle(Vec3 _pos, Vec3 _vel) {
			this(_pos, _vel, new Vec3(1), 120, 0);
		}

		public Particle(Vec3 _pos, Vec3 _vel, Vec3 _hue, float _lifespan, float _air_friction_coeff) {
			this.pos = new Vec3(_pos);
			this.vel = new Vec3(_vel);
			this.hue = new Vec3(_hue);
			this.lifespan = _lifespan;
			this.air_friction_coeff = _air_friction_coeff;
			this.is_static = false;
			this.coeff_restitution = 1;
		}
	}

