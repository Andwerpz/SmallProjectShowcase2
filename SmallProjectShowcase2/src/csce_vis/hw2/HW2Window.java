	@Override
	protected void _keyPressed(int key) {
		switch (key) {
		case GLFW.GLFW_KEY_Q:
			this.resetParticles();
			break;

		//lidar scanner
		case GLFW.GLFW_KEY_E: {
			float rand_coeff = 0.01f;
			Mat4 inv_camera = this.perspectiveScreen.getCamera().getInvViewMatrix();
			float vertical_fov = (float) Math.toRadians(90f);

			float dist = 5f;
			float ymax = dist * (float) Math.tan(vertical_fov / 2.0);
			float aspect_ratio = (float) this.getWidth() / (float) this.getHeight();
			float xmax = ymax * aspect_ratio;

			int y_cnt = 100;
			int x_cnt = (int) (y_cnt * aspect_ratio);

			float y_inc = (2.0f * ymax) / y_cnt;
			float x_inc = (2.0f * xmax) / x_cnt;

			float y_ptr = -ymax + y_inc / 2;
			for (int i = 0; i < y_cnt; i++, y_ptr += y_inc) {
				float x_ptr = -xmax + x_inc / 2;
				for (int j = 0; j < x_cnt; j++, x_ptr += x_inc) {
					float rx = rand_coeff * MathUtils.random(-1, 1);
					float ry = rand_coeff * MathUtils.random(-1, 1);

					Vec3 dir = new Vec3(x_ptr + rx, y_ptr + ry, -dist);
					dir.normalize();
					dir = inv_camera.mul(dir, 0);
					Vec3 camera_pos = this.perspectiveScreen.getCamera().getPos();

					Pair<Vec3, Material> ecoll = this.bvh.rayCollision(camera_pos, dir);
					if (ecoll == null) {
						continue;
					}

					Vec3 coll_pt = ecoll.first;
					//					coll_pt.subi(dir.mul(0.1f));
					Particle p = new Particle(coll_pt);
					p.hue = ecoll.second.getDiffuse().xyz();

					if (p.hue.y != 0) {
						p.proximity_hue = true;
					}

					this.generateParticle(p);
				}
			}
			break;
		}

		//'sound' grenade
		case GLFW.GLFW_KEY_G: {
			Vec3 color = new Vec3(57, 173, 72).mul(1.0f / 255.0f);

			Vec3 center = this.pic.getTop().add(this.pic.getFacing().mul(1));

			for (int i = 0; i < 30000; i++) {
				Vec3 dir = MathUtils.randomUnitDir();
				float vel = 6f;

				Particle p = new Particle(center, dir.mul(vel));
				p.lifespan = MathUtils.random(2, 5);
				p.air_friction_coeff = 0;
				p.hue = new Vec3(color);
				this.generateParticle(p);
			}
			break;
		}

		case GLFW.GLFW_KEY_P:
			pos_list.add(new Vec3(this.pic.getPos()));
			break;

		case GLFW.GLFW_KEY_O:
			for (Vec3 v : pos_list) {
				System.out.println(v);
			}
			break;

		case GLFW.GLFW_KEY_L:
			this.lightsOn = !this.lightsOn;
			break;

		case GLFW.GLFW_KEY_C:
			this.pic.setDoNoclip(false);
			break;

		case GLFW.GLFW_KEY_R:
			this.resetParticles();
			break;
		}
	}

