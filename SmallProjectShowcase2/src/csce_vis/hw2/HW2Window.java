	//just kill all particles
	private void resetParticles() {
		float[] pos_data = new float[MAX_PARTICLE_CNT * 4];
		for (int i = 0; i < MAX_PARTICLE_CNT; i++) {
			pos_data[i * 4 + 3] = -1; //set lifespan
		}
		this.posbo.setData(pos_data);

		this.activeParticles.clear();
	}

	//tries to generate whatever is inside genList
	//if it runs out of tries, then try to generate on next update
	private void _generateParticles() {
		for (int i = 0; i < GEN_MAX_TRIES && this.genList.size() != 0; i++) {
			float[] pos_data = new float[GEN_BATCH_SIZE * 4];
			float[] vel_data = new float[GEN_BATCH_SIZE * 4];
			float[] hue_data = new float[GEN_BATCH_SIZE * 4];
			float[] attr_data = new float[GEN_BATCH_SIZE * 4];

			this.posbo.getSubData(pos_data, this.genBytePtr);
			this.velbo.getSubData(vel_data, this.genBytePtr);
			this.huebo.getSubData(hue_data, this.genBytePtr);
			this.attrbo.getSubData(attr_data, this.genBytePtr);

			for (int j = 0; j < GEN_BATCH_SIZE && this.genList.size() != 0; j++) {
				if (pos_data[j * 4 + 3] > 0) {
					//still alive
					continue;
				}

				//put particle here
				Particle p = this.genList.poll();
				pos_data[j * 4 + 0] = p.pos.x;
				pos_data[j * 4 + 1] = p.pos.y;
				pos_data[j * 4 + 2] = p.pos.z;
				pos_data[j * 4 + 3] = p.lifespan;

				vel_data[j * 4 + 0] = p.vel.x;
				vel_data[j * 4 + 1] = p.vel.y;
				vel_data[j * 4 + 2] = p.vel.z;
				vel_data[j * 4 + 3] = p.air_friction_coeff;

				hue_data[j * 4 + 0] = p.hue.x;
				hue_data[j * 4 + 1] = p.hue.y;
				hue_data[j * 4 + 2] = p.hue.z;
				hue_data[j * 4 + 3] = p.is_static ? 1 : -1;

				attr_data[j * 4 + 0] = p.proximity_hue ? 1 : -1;
				attr_data[j * 4 + 1] = p.coeff_restitution;

				this.activeParticles.add(System.currentTimeMillis() + (int) (p.lifespan * 1000));
			}

			this.posbo.setSubData(pos_data, this.genBytePtr);
			this.velbo.setSubData(vel_data, this.genBytePtr);
			this.huebo.setSubData(hue_data, this.genBytePtr);
			this.attrbo.setSubData(attr_data, this.genBytePtr);

			this.genBytePtr = (this.genBytePtr + GEN_BATCH_SIZE * 4 * 4) % (MAX_PARTICLE_CNT * 4 * 4);
		}
	}

	private void generateParticle(Particle p) {
		this.genList.add(p);
	}

	@Override
	protected void _update() {
		this.pic.update();

		if (this.mousePressed) {
			for (int i = 0; i < (1 << 10); i++) {
				Vec3 pos = new Vec3(this.pic.getTop());
				Vec3 vel = new Vec3(this.pic.getFacing());
				vel.muli(MathUtils.random(8, 8.5f));
				float deviation = 0.4f * (float) Math.random();
				vel.addi(MathUtils.generateRandomPerpendicularVec3(vel).mul(deviation));
				Particle p = new Particle(pos, vel);
				p.lifespan = MathUtils.random(8, 12);
				p.coeff_restitution = MathUtils.random(0.8f, 1);
				this.generateParticle(p);
			}
		}

		//generate particles
		this._generateParticles();

		while (this.activeParticles.size() != 0 && this.activeParticles.peek() < System.currentTimeMillis()) {
			this.activeParticles.poll();
		}
		this.particleCountText.setText(this.activeParticles.size() + "");
		this.particleCountText.setWidth(this.particleCountText.getTextWidth());

		//update particles
		{
			this.particleUpdateShader.enable();
			this.particleUpdateShader.setUniform1i("compute_x_dim", COMPUTE_X_DIM);
			this.particleUpdateShader.setUniform1i("compute_y_dim", COMPUTE_Y_DIM);
			this.particleUpdateShader.setUniform1f("dt", Main.getDeltaSeconds());

			this.posbo.bindToBase(1);
			this.velbo.bindToBase(2);
			this.huebo.bindToBase(3);
			this.attrbo.bindToBase(4);

			this.bvh.getBVHSSBO().bindToBase(5);
			this.bvh.getBoundingBoxSSBO().bindToBase(6);
			this.bvh.getPrimitiveSSBO().bindToBase(7);

			glDispatchCompute(COMPUTE_X_DIM, COMPUTE_Y_DIM, 1);
		}
	}

	@Override
	protected void renderContent(Framebuffer outputBuffer) {
		Camera camera = new Camera((float) Math.toRadians(90), this.getWidth(), this.getHeight(), 0.1f, 400);
		camera.setPos(this.pic.getTop());
		camera.setFacing(this.pic.getFacing());
		Mat4 pr_matrix = camera.getProjectionMatrix();
		Mat4 vw_matrix = camera.getViewMatrix();

		this.perspectiveScreen.setCamera(camera);

		//render geometry
		if (this.lightsOn) {
			this.perspectiveScreen.render(outputBuffer);
		}

		//render particles
		{
			this.particleRenderShader.enable();
			this.particleRenderShader.setUniformMat4("pr_matrix", pr_matrix);
			this.particleRenderShader.setUniformMat4("vw_matrix", vw_matrix);
			this.particleRenderShader.setUniform3f("view_pos", this.pic.getTop());
			this.particleRenderShader.setUniform1i("do_gdt", this.lightsOn ? 1 : 0);

			this.perspectiveScreen.geometryPositionMap.bind(GL_TEXTURE0);

			this.posbo.bindToBase(1);
			this.velbo.bindToBase(2);
			this.huebo.bindToBase(3);
			this.attrbo.bindToBase(4);

			this.renderBuffer.bind();
			glClearDepth(1); // maximum value
			glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);

			glEnable(GL_DEPTH_TEST);
			glDepthFunc(GL_LESS);

			//			glEnable(GL_POINT_SMOOTH);
			//			glEnable(GL_BLEND);
			//			glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

			//			glPointSize(2f);
			glEnable(GL_PROGRAM_POINT_SIZE);
			glViewport(0, 0, this.getWidth(), this.getHeight());
			glDrawArrays(GL_POINTS, 0, MAX_PARTICLE_CNT);
		}

		//render back to output buffer
		{
			outputBuffer.bind();
			Shader.SPLASH.enable();
			Shader.SPLASH.setUniform1f("alpha", 1f);
			this.renderColorMap.bind(GL_TEXTURE0);
			ScreenQuad.screenQuad.render();
		}

		this.uiScreen.setUIScene(UI_SCENE);
		this.uiScreen.render(outputBuffer);
	}

